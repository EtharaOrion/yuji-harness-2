#!/usr/bin/env python3
"""Regenerate README.md from the harness code, so it cannot drift from it.

    python3 scripts/gen_readme.py           write README.md
    python3 scripts/gen_readme.py --check   exit 1 if README.md is stale

Every fact below is read from the file that owns it: the harbor pin from
scripts/lib/harbor.sh, the patches from scripts/patch_harbor.py, the usage and
environment from run_task.sh's header, the stages from its dispatch, the make
targets from the Makefile, and the tree from the files themselves. Prose here
only says how the pieces relate.
"""

from __future__ import annotations

import ast
import re
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
README = REPO / "README.md"


def harbor_pin() -> str:
    m = re.search(r'^HARBOR_VERSION="([^"]+)"', (REPO / "scripts/lib/harbor.sh").read_text(), re.M)
    return m.group(1) if m else "?"


def lock_size(path: Path) -> int:
    return sum(1 for ln in path.read_text().splitlines() if re.match(r"^[A-Za-z0-9_.-]+==", ln))


def patches() -> tuple[list[str], list[str]]:
    """(patch names, native behaviours) from patch_harbor.py's own constants."""
    tree = ast.parse((REPO / "scripts/patch_harbor.py").read_text())
    names, native = [], []
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and getattr(node.func, "id", None) == "Patch":
            for kw in node.keywords:
                if kw.arg == "name" and isinstance(kw.value, ast.Constant):
                    names.append(kw.value.value)
        if (isinstance(node, ast.Assign) and any(getattr(t, "id", None) == "NATIVE_REQUIRED"
                                                 for t in node.targets)):
            for elt in node.value.elts:
                native.append(elt.elts[2].value)
    return names, native


def run_task_header() -> str:
    lines = []
    for ln in (REPO / "scripts/run_task.sh").read_text().splitlines()[1:]:
        if not ln.startswith("#"):
            break
        lines.append(ln[2:] if ln.startswith("# ") else ln[1:])
    return "\n".join(lines).strip()


def stages() -> list[str]:
    body = (REPO / "scripts/run_task.sh").read_text()
    m = re.search(r'^  all\|([a-z|]+)\) ;;', body, re.M)
    return ["all", *m.group(1).split("|")] if m else []


def entry_points() -> dict[str, str]:
    return tomllib.loads((REPO / "pyproject.toml").read_text())["project"]["scripts"]


def cli_usage() -> str:
    doc = ast.get_docstring(ast.parse((REPO / "tools/cli.py").read_text())) or ""
    return doc.split("\n\n")[1] if "\n\n" in doc else doc


def make_targets() -> list[tuple[str, str]]:
    out = []
    for ln in (REPO / "Makefile").read_text().splitlines():
        m = re.match(r"^([a-z][a-z0-9-]*):[^=]*#\s*(.+)$", ln)
        if m:
            out.append((m.group(1), m.group(2).strip()))
    return out


TREE = (
    ("pyproject.toml", "the registered entry points and the pinned harbor; uv.lock beside it"),
    ("tools/cli.py", "harness-infer and harness-eval"),
    ("scripts/run_task.sh", "one task end to end: preflight, harbor, reshape, finance, mask"),
    ("scripts/run_batch.py", "every task x every attempt through run_task.sh's stages, checkpointed"),
    ("scripts/lib/harbor.sh", "the harbor pin and its hash-checked install"),
    ("scripts/lib/harbor-requirements.lock", "harbor's whole dependency closure, with hashes"),
    ("scripts/patch_harbor.py", "the edits made to the pinned harbor, each one or a loud refusal"),
    ("scripts/checkpoint.py", "the batch checkpoint run_batch.py resumes from"),
    ("scripts/stop_harness.sh", "stop the harness's bridges and sweep orphaned trial containers"),
    ("scripts/gen_readme.py", "this README"),
    ("tools/openhands_agent/", "the default agent under test: OpenHands behind harbor's agent interface"),
    ("tools/bridges/", "host-side model routes: ccbridge (Claude subscription), zbridge (GLM)"),
    ("tools/headroom/", "optional agent-path prompt compression (AGENT_HEADROOM_ENABLED)"),
    ("tools/network/", "network preflight against harbor's resolver, egress guard hook, internet audit"),
    ("tools/delivery_utils/", "reshape harbor's job dir into the per-task output tree; package deliveries"),
    ("tools/finance/", "usage reporting to Odoo after a run"),
    ("services/", "the upstream MCP-Atlas REST pipeline (agent-environment, agent-harness, "
                  "mcp_eval, diagnostics, legacy scoring)"),
)


def present(path: str) -> bool:
    return (REPO / path.rstrip("/")).exists()


def render() -> str:
    names, native = patches()
    lock = REPO / "scripts/lib/harbor-requirements.lock"
    out = []
    w = out.append
    w("# harness: the benchmark extension for the resident bundles\n")
    w("<!-- Generated by scripts/gen_readme.py from the harness code. Do not edit by hand;\n"
      "     edit the source the section names and run `python3 scripts/gen_readme.py`. -->\n")
    w("Runs inference and evaluation over the task bundles with "
      f"[Harbor](https://github.com/harbor-framework/harbor) **{harbor_pin()}**. "
      "Each bundle is self-contained: its `task.toml` declares the network policy of every "
      "phase and where its verifier runs, and its own `tests/` score the run. The harness adds "
      "the agent under test, a model route on the host, and the bookkeeping around a run. It "
      "carries no grader, no judge and no network proxy of its own.\n")

    w("## What the bundle owns, and what the harness adds\n")
    w("| Concern | Owner | Mechanism |\n|---|---|---|")
    w("| Scoring | bundle | `tests/` run by harbor in the verifier environment; the reshaper "
      "publishes `verifier/reward.json` as written and never recomputes it |")
    w("| Verifier environment | bundle | `[verifier] environment_mode` (`separate`: built from "
      "`[verifier.environment].docker_image`, else `tests/Dockerfile`, else `[environment]`) |")
    w("| Network policy | bundle | `network_mode` in `[environment]`, `[agent]`, `[verifier]`, "
      "enforced by harbor's docker egress-control sidecar, which refuses a trial it cannot enforce |")
    w("| Model route | harness | a bridge on the host, passed to harbor as `--allow-agent-host` |")
    w("| Agent under test | harness | `tools/openhands_agent` (default) or harbor's `claude-code` |")
    w("| Agent-side egress layers | harness | `--disallowedTools` and a PreToolUse guard, only "
      "when the task closes its agent phase; the internet audit afterwards |\n")
    w("Trial-level `--extra-docker-compose` and `--mounts` reach the agent environment only, so "
      "nothing the harness adds touches a separate verifier.\n")

    w("## Entry points\n")
    w("Registered in `pyproject.toml` under `[project.scripts]` and locked in `uv.lock`:\n")
    w("| Script | Target |\n|---|---|")
    for name, target in entry_points().items():
        w(f"| `{name}` | `{target}` |")
    w("\n```text\n" + cli_usage() + "\n```\n")
    w("Inference is `scripts/run_task.sh`. Evaluation is `harbor trial regrade --task-path "
      "<bundle>`: it seeds a new trial with the recorded agent logs and artifacts and runs the "
      "bundle's own `tests/` in a separate verifier environment, leaving the source trial "
      "untouched. Harbor refuses to regrade a task whose verifier is in shared mode.\n")

    w("## Harbor\n")
    w(f"Pinned at **{harbor_pin()}** in `scripts/lib/harbor.sh` and installed from "
      f"`scripts/lib/harbor-requirements.lock` ({lock_size(lock)} packages, every file "
      "hash-checked with `--require-hashes`):\n")
    w("```bash\nmake install-harbor          # bash scripts/lib/harbor.sh install\n```\n")
    w("`scripts/patch_harbor.py` runs before every harbor stage. It refuses any harbor other "
      "than the pin, applies each patch or reports it as a MISS and exits 1, and is idempotent. "
      "Patches applied:\n")
    for n in names:
        w(f"- {n}")
    w("\nBehaviour it requires harbor to provide natively (checked, never patched):\n")
    for n in native:
        w(f"- {n}")
    w("")

    w("## Running a task\n")
    w("From `scripts/run_task.sh`:\n")
    w("```text\n" + run_task_header() + "\n```\n")
    w("Stages: " + ", ".join(f"`{s}`" for s in stages()) + ". "
      "`scripts/run_batch.py` drives them one at a time with a checkpoint between each.\n")
    w("Before the agent phase, `tools/network/preflight_network.py` resolves the task's network "
      "plan and verifier environment through harbor's own code and refuses what harbor would "
      "refuse after the image build.\n")

    w("## Make targets\n")
    w("| Target | What it does |\n|---|---|")
    for t, d in make_targets():
        w(f"| `make {t}` | {d} |")
    w("")

    w("## Layout\n")
    w("| Path | Role |\n|---|---|")
    for path, role in TREE:
        if present(path):
            w(f"| `{path}` | {role} |")
    w("")

    w("## Tests\n")
    w("```bash\nuv run --no-project --with pytest --with pyyaml python -m pytest scripts/tests\n```\n")
    w("Tests that need Docker, an installed harbor, or credentials skip themselves when those "
      "are absent. `scripts/tests/test_readme.py` fails when this file is stale.\n")
    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if README.read_text() != text:
            print("README.md is stale: run python3 scripts/gen_readme.py", file=sys.stderr)
            return 1
        return 0
    README.write_text(text)
    print(f"wrote {README}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
